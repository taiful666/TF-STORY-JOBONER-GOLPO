#!/usr/bin/env python3
"""Builds CODEMAP.md: a line-numbered index of every section and function in the app.

Run after every change:  python3 tools/codemap.py
Claude reads CODEMAP.md (small) instead of index.html (10k+ lines), then opens only the
lines it needs with Read(offset, limit). Line numbers are refreshed by this script.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'CODEMAP.md')

# files to index (vendor libs and the bundled mp4 muxer are skipped)
FILES = [
    'home.html', 'index.html', 'cloud-core.js', 'long-library.js', 'long-visuals.js', 'sw.js',
    'fx/motion.js', 'fx/shadow.js',
    'explainer/paper.js', 'explainer/part.js',
    'islamic/index.html', 'islamic/story.js', 'islamic/art.js', 'islamic/art2.js',
    'islamic/stories-1.js', 'islamic/stories-2.js', 'islamic/stories-3.js',
    'android/app/src/main/java/com/taiful/tfstory/MainActivity.kt',
    'android/app/src/main/java/com/taiful/tfstory/WebBridge.kt',
    'android/app/src/main/java/com/taiful/tfstory/Updater.kt',
    'android/app/src/main/java/com/taiful/tfstory/GoogleSignIn.kt',
    'android/app/src/main/java/com/taiful/tfstory/TFApp.kt',
]

SEC_BIG = re.compile(r'^\s*/\*\s*={3,}\s*(.+?)\s*(?:={3,}\s*)?(?:\*/)?\s*$')
SEC_SMALL = re.compile(r'^\s*/\*\s*-{3,}\s*(.+?)\s*(?:-{3,}\s*)?(?:\*/)?\s*$')
BLOCK = re.compile(r'^\s*<(script|style)\b([^>]*)>(.{0,90})', re.I)
FUNC = re.compile(r'^(\s{0,2})(?:async\s+)?function\s*\*?\s*([A-Za-z_$][\w$]*)\s*\(')
ARROW = re.compile(r'^(\s{0,2})(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=\s*(?:async\s*)?(?:\([^)]*\)|[A-Za-z_$][\w$]*)\s*=>')
OBJ = re.compile(r'^(?:const|let|var)\s+([A-Z_][A-Z0-9_]{2,}|[A-Za-z_$][\w$]*)\s*=\s*[\[{]')
KT = re.compile(r'^\s*(?:(?:private|internal|override|suspend|public)\s+)*(fun|class|object)\s+([A-Za-z_][\w.]*)')
SKIP_RANGES = {'index.html': []}


def clean(t, n=90):
    t = re.sub(r'\s+', ' ', t.replace('*/', '')).strip(' =-—')
    return t[:n] + ('…' if len(t) > n else '')


def index_file(rel):
    path = os.path.join(ROOT, rel)
    if not os.path.exists(path):
        return None
    lines = open(path, encoding='utf-8', errors='replace').read().split('\n')
    out = []  # (kind, line, text)
    skip = False
    for i, raw in enumerate(lines, 1):
        line = raw if len(raw) < 400 else raw[:400]
        if 'mp4-muxer' in line and '<script' in line:
            out.append(('block', i, 'bundled mp4-muxer (library — do not edit)')); skip = True; continue
        if skip:
            if '</script>' in line:
                skip = False
            continue
        m = BLOCK.match(line)
        if m and rel.endswith('.html'):
            tag, attrs, rest = m.groups()
            if 'base64' in line:
                rest = 'embedded font (base64)'
            idm = re.search(r'(?:id|src)="([^"]+)"', attrs)
            out.append(('block', i, f'<{tag}{" " + idm.group(1) if idm else ""}> {clean(rest, 70)}'))
        m = SEC_BIG.match(line)
        if m:
            out.append(('H', i, clean(m.group(1)))); continue
        m = SEC_SMALL.match(line)
        if m:
            out.append(('h', i, clean(m.group(1)))); continue
        if rel.endswith('.kt'):
            m = KT.match(line)
            if m:
                out.append(('f', i, f'{m.group(1)} {m.group(2)}'))
            continue
        m = FUNC.match(line) or ARROW.match(line)
        if m:
            out.append(('f', i, m.group(2))); continue
        m = OBJ.match(line)
        if m:
            out.append(('c', i, m.group(1)))
    return len(lines), out


def html_ids(rel):
    path = os.path.join(ROOT, rel)
    txt = open(path, encoding='utf-8', errors='replace').read()
    body = txt
    ids = []
    for m in re.finditer(r'<(?:div|section|button|input|select|textarea|canvas|span|label|nav|aside|main|header|dialog)\b[^>]*\bid="([^"]+)"', body):
        ln = body.count('\n', 0, m.start()) + 1
        ids.append((ln, m.group(1)))
    return ids


def main():
    md = ['# CODEMAP — auto-generated by `python3 tools/codemap.py` (do not edit by hand)', '',
          'Format: `line` name. **H** = big section, *h* = sub-section, then functions / constants under it.',
          'Open code with Read(file, offset=line, limit=…) — never read a big file whole.', '']
    for rel in FILES:
        r = index_file(rel)
        if not r:
            continue
        n, items = r
        md.append(f'## {rel}  ({n} lines)')
        buf = []
        def flush():
            if buf:
                md.append('  ' + ' · '.join(buf)); buf.clear()
        for kind, ln, text in items:
            if kind == 'block':
                flush(); md.append(f'- `{ln}` ▸ {text}')
            elif kind == 'H':
                flush(); md.append(f'- `{ln}` **{text}**')
            elif kind == 'h':
                flush(); md.append(f'  - `{ln}` *{text}*')
            elif kind in ('f', 'c'):
                buf.append(f'`{ln}` {text}')
                if len(buf) >= 8:
                    flush()
        flush()
        if rel.endswith('.html'):
            ids = html_ids(rel)
            if ids:
                md.append(f'  - element ids ({len(ids)}): ' + ' · '.join(f'{i}@{l}' for l, i in ids[:400]))
        md.append('')
    open(OUT, 'w', encoding='utf-8').write('\n'.join(md) + '\n')
    print(f'CODEMAP.md written ({sum(1 for l in md)} lines)')


if __name__ == '__main__':
    main()
